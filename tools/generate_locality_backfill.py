"""Generate the immutable whole-name SQL backfill for the 2026-10-25 PIBA snapshot."""

import argparse
import hashlib
import json
import re
import unicodedata
from pathlib import Path

CATALOG = Path(__file__).resolve().parents[1] / "apps/api/src/Movely.Api/Modules/Localities/Data/localities.piba.2026-10-25.json"
EXPECTED_SHA256 = "5eeaa35474b6327de57bad5ff367a2c3b9739d4e1d8d65d18c97ea28fc6fc9a0"
BEGIN = "        // BEGIN PINNED LOCALITY BACKFILL"
END = "        // END PINNED LOCALITY BACKFILL"
LOWER_ASCII = str.maketrans("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz")


def sql():
    raw = CATALOG.read_bytes()
    if hashlib.sha256(raw).hexdigest() != EXPECTED_SHA256:
        raise ValueError("The pinned source changed. Never regenerate a historical migration from a newer catalog.")
    names = {}
    for locality in json.loads(raw):
        for name in [locality["name"], *locality["aliases"]]:
            normalized = re.sub(r"\s+", " ", unicodedata.normalize("NFC", name).strip()).translate(LOWER_ASCII)
            names.setdefault(normalized, set()).add(locality["code"])
    resolved = sorted((name, next(iter(codes))) for name, codes in names.items() if len(codes) == 1)
    ambiguous = sorted(name for name, codes in names.items() if len(codes) > 1)
    if len(ambiguous) != 4:
        raise ValueError("Unexpected ambiguity count in pinned source.")

    def literal(value):
        return "'" + value.replace("'", "''") + "'"

    values = ",\n".join(f"                ({literal(name)}, {literal(code)})" for name, code in resolved)
    return f'''{BEGIN}
        // PIBA 2026-10-25, catalog SHA256 {EXPECTED_SHA256}.
        // {len(resolved)} whole-name aliases; all four cross-code ambiguous names are excluded.
        // Generated by tools/generate_locality_backfill.py; never use a live catalog here.
        migrationBuilder.Sql("""
            SET LOCAL standard_conforming_strings = on;
            WITH aliases(name, code) AS (
                VALUES
{values}
            )
            UPDATE "MoveLocations" AS location
            SET "CanonicalLocalityCode" = aliases.code
            FROM aliases
            WHERE location."CanonicalLocalityCode" IS NULL
              AND location."City" IS NOT NULL
              AND char_length(location."City") <= 120
              AND translate(
                    btrim(regexp_replace(normalize(location."City", NFC),
                      U&'[\\0009-\\000D\\0020\\0085\\00A0\\1680\\2000-\\200A\\2028\\2029\\202F\\205F\\3000]+', ' ', 'g')),
                    'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz') COLLATE "C"
                  = aliases.name COLLATE "C";
            """);
{END}'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--migration", type=Path, help="Replace the marked SQL block in this migration.")
    parser.add_argument("--check", action="store_true", help="Require that the existing migration block is reproducible.")
    args = parser.parse_args()
    generated = sql()
    if args.migration is None:
        print(generated)
        return
    source = args.migration.read_text(encoding="utf-8-sig")
    start = source.index(BEGIN)
    end = source.index(END, start) + len(END)
    if args.check:
        if source[start:end] != generated:
            raise ValueError("Migration SQL differs from its pinned deterministic generator.")
        print("Pinned locality backfill is reproducible.")
    else:
        args.migration.write_text(source[:start] + generated + source[end:], encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
